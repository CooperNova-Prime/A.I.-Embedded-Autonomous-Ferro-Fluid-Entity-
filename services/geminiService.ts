/**
 * Calculates exact mathematical spherical metrics for regulation tennis ball
 * (Diameter 6.70 cm, Radius 3.35 cm)
 */
export function calculateTennisBallMetrics(diameter_cm: number = 6.7): TennisBallMetrics {
  const radius_cm = diameter_cm / 2;
  const circumference_cm = 2 * Math.PI * radius_cm;
  const surface_area_cm2 = 4 * Math.PI * Math.pow(radius_cm, 2);
  const volume_cm3 = (4 / 3) * Math.PI * Math.pow(radius_cm, 3);

  return {
    diameter_cm,
    radius_cm,
    circumference_cm,
    surface_area_cm2,
    volume_cm3,
  };
}

/**
 * Builds the exact prompt as requested:
 * Provide a visual breakdown of a tennis ball with these spherical dimensions:
 * - Diameter: {diameter_cm:.2f} cm
 * - Perimeter / Circumference: {circumference_cm:.2f} cm
 * - Surface Area: {surface_area_cm2:.2f} cm²
 * - Volume: {volume_cm3:.2f} cm³
 */
export function buildTennisBallPrompt(metrics: TennisBallMetrics): string {
  return `Provide a visual breakdown of a tennis ball with these spherical dimensions:
- Diameter: ${metrics.diameter_cm.toFixed(2)} cm
- Perimeter / Circumference: ${metrics.circumference_cm.toFixed(2)} cm
- Surface Area: ${metrics.surface_area_cm2.toFixed(2)} cm²
- Volume: ${metrics.volume_cm3.toFixed(2)} cm³`;
}

